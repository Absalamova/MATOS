// Helper to re-order family array so the item's own color comes first
function withPrimaryColor(family: ColorOption[], primaryId: string): ColorOption[] {
  const primary = family.find((c) => c.id === primaryId || c.fabricId === primaryId);
  if (!primary) return family;
  const others = family.filter((c) => c !== primary);
  return [primary, ...others];
}

